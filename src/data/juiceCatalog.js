export function listJuices(type = "all") {
  if (type === "juice") return JUICE_CATALOG.filter((j) => j.type === "juice");
  if (type === "smoothie") return JUICE_CATALOG.filter((j) => j.type === "smoothie");
  return [...JUICE_CATALOG];
}

export function getJuiceById(id) {
  const raw = String(id).replace(/^juice-/, "");
  const item = JUICE_CATALOG.find((j) => j.id === raw);
  if (!item) return null;
  return {
    id: `juice-${item.id}`,
    externalId: item.id,
    name: item.title,
    title: item.title,
    description: item.description,
    image: item.image,
    ingredients: [],
    type: item.type,
    source: "juice-catalog",
  };
}

export function searchJuices(query) {
  const q = query.trim().toLowerCase();
  return listJuices("all")
    .map((item) => getJuiceById(item.id))
    .filter(
      (d) =>
        !q ||
        d.title.toLowerCase().includes(q) ||
        d.description.toLowerCase().includes(q)
    );
}
